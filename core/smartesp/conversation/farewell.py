"""Прощание: человек заканчивает разговор — Кузя молчит, ничего не спрашивает.

Маленькая модель на «всё, пока» отвечает длинно и часто сама задаёт вопрос, а вопрос
включает прослушивание — разговор не кончается. Поэтому прощание узнаётся до модели:
реплика целиком из слов прощания (и связок), хотя бы одно — явное прощание. Тогда ход
кончается без ответа и без записи в историю.
"""

import re

# явные слова конца разговора; «все» — «всё» без точек над ё
_STRONG = frozenset(
    "пока всё все хватит отбой свидания ночи доброго достаточно свободен свободна отдыхай "
    "закончим заканчиваем ничего".split()
)
# слова, которые не меняют смысл прощания («ну всё, спасибо, пока», «больше ничего не нужно»)
_SOFT = frozenset(
    "ну спасибо спасибочки благодарю ладно ок окей хорошо понял поняла ясно давай давайте до на "
    "этом сегодня тогда всего хорошего спокойной больше не нужно надо кузя миранда и а так".split()
)
_WORDS = re.compile(r"[а-яёa-z]+")
_MAX_WORDS = 8  # длиннее — это уже не прощание, а просьба


def is_farewell(text: str) -> bool:
    """True, если реплика — только прощание («всё, пока», «спасибо, хватит», «спокойной ночи»)."""
    words = _WORDS.findall(text.lower())
    if not words or len(words) > _MAX_WORDS:
        return False
    return any(w in _STRONG for w in words) and all(w in _STRONG or w in _SOFT for w in words)
