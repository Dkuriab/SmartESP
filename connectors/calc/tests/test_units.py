BAD_CASES = [
    (1, "стакан", "г", "", "продукт"),
    (1, "г", "мл", "", "продукт"),
    (1, "стакан", "г", "картофель", "картофель"),
    (1, "парсек", "г", "", "парсек"),
    (1, "г", "аршин", "", "аршин"),
    (1, "°C", "г", "", "температур"),
    (1, "кг", "°F", "мука", "температур"),
    (-300, "°C", "°F", "", "абсолютн"),
    (-500, "°F", "°C", "", "абсолютн"),
    (1, "стакан", "г", "картофель", "знаю: мука"),
    (float("inf"), "кг", "г", "", "числом"),
    (float("nan"), "кг", "г", "", "числом"),
    (1e308, "кг", "мг", "", "больш"),
]


@pytest.mark.parametrize(("value", "src", "dst", "product", "fragment"), BAD_CASES)
def test_convert_bad(value: float, src: str, dst: str, product: str, fragment: str) -> None:
    with pytest.raises(UnitError) as info:
        convert(value, src, dst, product)
    assert fragment in str(info.value).lower()


@pytest.mark.parametrize(
    ("total", "parts", "unit", "expected"),
    [
        (500, 10, "г", "500 граммов на 10 — по 50 граммов"),
        (500, 10, "", "500 на 10 — по 50"),
        (1, 3, "кг", "1 килограмм на 3 — по 0,3333 килограмма"),
        (1, 1, "л", "1 литр на 1 — по 1 литр"),
        (10, 4, "стаканов", "10 стаканов на 4 — по 2,5 стакана"),
        (7.5, 2, "ст. л.", "7,5 столовой ложки на 2 — по 3,75 столовой ложки"),
        (500, 10, "порций", "500 порций на 10 — по 50 порций"),
    ],
)
def test_split_ok(total: float, parts: int, unit: str, expected: str) -> None:
    assert split(total, parts, unit) == expected


def test_split_not_finite() -> None:
    with pytest.raises(UnitError):
        split(float("inf"), 2, "г")


@pytest.mark.parametrize(("parts", "fragment"), [(0, "частей"), (-2, "частей"), (100001, "частей")])
def test_split_bad(parts: int, fragment: str) -> None:
    with pytest.raises(UnitError) as info:
        split(10, parts, "г")
    assert fragment in str(info.value).lower()
