    ("7 × 6", "42"),
    ("9 ÷ 2", "4,5"),
    ("sqrt(16)", "4"),
    ("sqrt(2)", "1,4142"),
    ("abs(-3.5)", "3,5"),
    ("round(2.567, 2)", "2,57"),
    ("round(2.5)", "3"),
    ("round(0.5)", "1"),
    ("round(-2.5)", "-3"),
    ("round(1.005, 2)", "1,01"),
    ("3 ** 60", "42391158275216203514294433201"),
    ("123456789012345678 * 10", "1234567890123456780"),
    ("9007199254740993 + 0", "9007199254740993"),
    ("9007199254740993 * 3", "27021597764222979"),
